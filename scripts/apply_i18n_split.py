#!/usr/bin/env python3
"""Split js/i18n.js: move the monolithic translations object out of the engine.
Engine keeps only the loader + code; per-locale chunks are emitted by build_i18n.py
into js/i18n/{lang}.js. Pages then load the engine (~15 KB) + one locale chunk
instead of one 128 KB file. Run once; afterwards build_i18n.py owns the chunks."""
import re, sys, pathlib

BASE = pathlib.Path(__file__).resolve().parent.parent
F = BASE / "js" / "i18n.js"
s = F.read_text(encoding="utf-8")

# 1) Replace the giant translations object with the chunk loader.
start = s.index("const translations = {")
end = s.index("\n};", start) + len("\n};")
loader = """// Per-locale translation chunks live in /js/i18n/{lang}.js — generated by
// scripts/build_i18n.py from locales/ui/*.json. The engine loads ONLY the chunk
// for the current language instead of one monolithic file for all five.
const translations = {};
const I18N_CHUNK_DIR = '/js/i18n';
const I18N_V = '__I18N_BUILD__';
const _i18nChunkPromises = {};
function loadI18nChunk(lang) {
  if (translations[lang]) return Promise.resolve();
  if (_i18nChunkPromises[lang]) return _i18nChunkPromises[lang];
  _i18nChunkPromises[lang] = new Promise((resolve) => {
    const s = document.createElement('script');
    s.src = I18N_CHUNK_DIR + '/' + lang + '.js?v=' + I18N_V;
    s.onload = resolve;
    s.onerror = resolve; // a missing chunk must not block boot; fallback logic handles it
    document.head.appendChild(s);
  });
  return _i18nChunkPromises[lang];
}"""
s = s[:start] + loader + s[end:]

# 2) currentLang detection: drop the translations[staticLang] check (chunk not loaded yet).
old_detect = """  const staticLang = document.documentElement.getAttribute('data-i18n-static');
  if (staticLang && translations[staticLang]) {
    currentLang = staticLang;
    try { localStorage.setItem('ms_lang', staticLang); } catch (e) {}
  } else if (m) {"""
new_detect = """  const staticLang = document.documentElement.getAttribute('data-i18n-static');
  if (staticLang) {
    currentLang = staticLang;
    try { localStorage.setItem('ms_lang', staticLang); } catch (e) {}
  } else if (m) {"""
if old_detect not in s:
    sys.exit("detect block not found")
s = s.replace(old_detect, new_detect)

# 3) switchLanguage: ensure the target chunk is loaded before switching.
old_switch = """function switchLanguage(lang) {
  if (!translations[lang]) lang = 'en';
  currentLang = lang;"""
new_switch = """function switchLanguage(lang) {
  return loadI18nChunk(lang).then(function () {
  if (!translations[lang]) lang = 'en';
  currentLang = lang;"""
if old_switch not in s:
    sys.exit("switchLanguage head not found")
s = s.replace(old_switch, new_switch)
# close the .then() wrapper before "applyTranslations();" at the end of switchLanguage
old_tail = """  applyTranslations();
  if (typeof loadDynamicPostsHome === 'function') loadDynamicPostsHome();
  if (typeof renderBlogIndexPosts === 'function') renderBlogIndexPosts();
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}"""
new_tail = """  applyTranslations();
  if (typeof loadDynamicPostsHome === 'function') loadDynamicPostsHome();
  if (typeof renderBlogIndexPosts === 'function') renderBlogIndexPosts();
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
  });
}"""
if old_tail not in s:
    sys.exit("switchLanguage tail not found")
s = s.replace(old_tail, new_tail, 1)  # first occurrence only (switchLanguage's tail)

# 4) Boot: await the current-language chunk before applying anything.
old_boot = """// Initialize
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', () => {
    initScrollObserver();
    applyTranslations();"""
new_boot = """// Initialize — the locale chunk must be loaded before any translation applies
function bootI18n() {
  loadI18nChunk(currentLang).then(() => {
    if (!translations[currentLang]) currentLang = 'en';
    initScrollObserver();
    applyTranslations();"""
if old_boot not in s:
    sys.exit("boot head not found")
s = s.replace(old_boot, new_boot)
old_boot2 = """    } else {
      setTimeout(loadDynamicPostsHome, 50);
      setTimeout(renderBlogIndexPosts, 50);
    }
  });
} else {
  initScrollObserver();
  applyTranslations();
  if ('requestIdleCallback' in window) {
    requestIdleCallback(loadDynamicPostsHome);
    requestIdleCallback(renderBlogIndexPosts);
  } else {
    setTimeout(loadDynamicPostsHome, 50);
    setTimeout(renderBlogIndexPosts, 50);
  }
}"""
new_boot2 = """    } else {
      setTimeout(loadDynamicPostsHome, 50);
      setTimeout(renderBlogIndexPosts, 50);
    }
  });
}
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', bootI18n);
} else {
  bootI18n();
}"""
if old_boot2 not in s:
    sys.exit("boot tail not found")
s = s.replace(old_boot2, new_boot2)

F.write_text(s, encoding="utf-8")
print("i18n.js split applied: loader in engine, translations moved to chunks")
