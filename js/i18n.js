async function loadDynamicPostsHome() {
try {
const res = await fetch('blog/posts.json');
if (!res.ok) return;
const posts = await res.json();
if (!Array.isArray(posts) || posts.length === 0) return;
const container = document.getElementById('homeBlogGrid');
const isSk = currentLang === 'sk';
const d = translations[currentLang] || translations.en;

container.innerHTML = posts.slice(0, 3).map(p => {
const title = (isSk && p.titleSk) ? p.titleSk : p.title;
const excerpt = (isSk && p.excerptSk) ? p.excerptSk : p.excerpt;
const date = (isSk && p.displayDateSk) ? p.displayDateSk : p.displayDate;
const targetUrl = (isSk && p.urlSk) ? p.urlSk : p.url;
return `
<a href="${targetUrl}" class="blog-card fade-in visible">
  <div class="blog-card-date">${date}</div>
  <h3>${title}</h3>
  <p>${excerpt}</p>
  <div class="blog-card-arrow">${d.blogReadPost || (isSk ? 'Čítať článok' : 'Read post')} <span>→</span></div>
</a>`;
}).join('');
} catch(e){}
}
const observer = new IntersectionObserver((entries) => {
entries.forEach(entry => {
if (entry.isIntersecting) entry.target.classList.add('visible');
});
}, { threshold: 0.1 });
document.querySelectorAll('.fade-in').forEach(el => observer.observe(el));
document.querySelectorAll('a[href^="#"]').forEach(anchor => {
anchor.addEventListener('click', function(e) {
const targetId = this.getAttribute('href');
if (targetId === '#') return;
const target = document.querySelector(targetId);
if (target) {
e.preventDefault();
target.scrollIntoView({ behavior: 'smooth' });
document.querySelector('.nav-links')?.classList.remove('open');
const toggle = document.querySelector('.mobile-toggle');
if (toggle) toggle.setAttribute('aria-expanded', 'false');
}
});
});
document.querySelector('.mobile-toggle')?.addEventListener('click', function() {
const nav = document.querySelector('.nav-links');
const isOpen = nav.classList.toggle('open');
this.setAttribute('aria-expanded', isOpen);
});
document.addEventListener('click', function(e) {
const nav = document.querySelector('.nav-links');
const toggle = document.querySelector('.mobile-toggle');
if (nav && nav.classList.contains('open') && !nav.contains(e.target) && !toggle.contains(e.target)) {
nav.classList.remove('open');
toggle?.setAttribute('aria-expanded', 'false');
}
});
if (currentLang === 'sk') {
  applyTranslations();
} else {
  document.getElementById('btnEn')?.classList.add('active');
  document.getElementById('btnSk')?.classList.remove('active');
}

if ('requestIdleCallback' in window) {
  requestIdleCallback(loadDynamicPostsHome);
} else {
  setTimeout(loadDynamicPostsHome, 300);
}

// Lead form — fetch submission (no iframe, works with X-Frame-Options:DENY)
document.getElementById('leadForm')?.addEventListener('submit', async function(e) {
  e.preventDefault();
  const btn = document.getElementById('subscribeBtn');
  const status = document.getElementById('leadStatus');
  const email = document.getElementById('leadEmail')?.value.trim();
  if (!email) return;
  btn.disabled = true;
  btn.textContent = 'Subscribing...';
  status.textContent = '';
  status.className = 'lead-status';
  try {
    const res = await fetch('/api/subscribe', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ email, source: 'marianstancik.dev' })
    });
    const data = await res.json();
    if (res.ok && data.status === 'ok') {
      status.textContent = '✅ Subscribed! Check your inbox.';
      status.className = 'lead-status lead-success';
      document.getElementById('leadEmail').value = '';
    } else {
      status.textContent = '❌ ' + (data.error || 'Something went wrong. Try again.');
      status.className = 'lead-status lead-error';
    }
  } catch (err) {
    status.textContent = '❌ Network error. Please try again.';
    status.className = 'lead-status lead-error';
  }
  btn.disabled = false;
  btn.textContent = currentLang === 'sk' ? 'Odoberať' : 'Subscribe';
});

